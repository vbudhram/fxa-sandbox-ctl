#!/usr/bin/env python3
"""Write the dashboard's component CSS for the design system: python3 dashboard/ds-sync.py <out.css>"""
import pathlib, re, sys

page = pathlib.Path(__file__).with_name("index.html").read_text()
css = re.search(r"<style>(.*?)</style>", page, re.S).group(1)

# Split into top-level "prelude { body }" blocks; comments before a block go with it.
blocks, depth, start = [], 0, 0
for i, c in enumerate(css):
    if c == "{": depth += 1
    elif c == "}":
        depth -= 1
        if depth == 0: blocks.append(css[start:i + 1].strip()); start = i + 1

# tokens.css sets colors, spacing, radius, shadows and layout; it has no type scale or font stacks, so those stay.
# ponytail: a fixed list of names, read tokens.json if a new :root value is not a token.
KEEP = re.compile(r"--(t-[\w-]+|sans|head|mono):[^;]+;")
out, kept = ["/* Generated by dashboard/ds-sync.py from dashboard/index.html. Do not edit. */"], []
for b in blocks:
    prelude = re.sub(r"/\*.*?\*/", "", b.split("{", 1)[0], flags=re.S).strip()
    if ":root" in prelude or (prelude.startswith("@media") and b.split("{", 1)[1].strip().startswith(":root")):
        kept += [m.group(0) for m in KEEP.finditer(b)]
        continue
    if prelude == "html, body": continue  # height:100% only fits the full page
    if prelude == "body": b = b.replace(" overflow:hidden;", "")
    out.append(b)
out.insert(1, ":root { " + " ".join(kept) + " }")
pathlib.Path(sys.argv[1]).write_text("\n".join(out) + "\n")
