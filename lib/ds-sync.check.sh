#!/usr/bin/env bash
# Offline check for dashboard/ds-sync.py: the design-system CSS has the components and no color tokens.
#   bash lib/ds-sync.check.sh
set -u
fail=0
check() { # check <name> <want> <got>
  if [ "$2" = "$3" ]; then printf 'ok   %s\n' "$1"
  else printf 'FAIL %s: want [%s] got [%s]\n' "$1" "$2" "$3"; fail=1; fi
}
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
here="$(cd "$(dirname "$0")" && pwd)"
python3 "$here/../dashboard/ds-sync.py" "$tmp/b.css"; check "the script runs" 0 $?
css="$(cat "$tmp/b.css" 2>/dev/null)"
check "the first line says it is generated" 1 "$(head -1 <<< "$css" | grep -c 'Generated by dashboard/ds-sync.py from dashboard/index.html')"
check "no theme or color token declarations" 0 "$(grep -cE 'data-theme|prefers-color-scheme|--(bg|panel|ink|ok):' <<< "$css")"
check "no page shell rules" "0|0" "$(grep -c '^html, body' <<< "$css")|$(awk '/^body \{/,/\}/' <<< "$css" | grep -c 'overflow:hidden')"
check "keeps .tag, .card and .table" "1|1|1" "$(grep -cm1 '^ *\.tag {' <<< "$css")|$(grep -cm1 '^ *\.card {' <<< "$css")|$(grep -cm1 '^ *\.table {' <<< "$css")"
check "keeps the type scale" 1 "$(grep -c '^:root { --t-tiny:11px;' <<< "$css")"
[ "$fail" = 0 ] && echo "all checks pass"; exit "$fail"
